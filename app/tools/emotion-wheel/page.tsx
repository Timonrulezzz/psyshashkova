/* =========================================
   MAP
========================================= */

function EmotionMap({
  activeKey,
  selectedKey,
  onHover,
  onSelect,
}: {
  activeKey: string | null;
  selectedKey: string | null;

  onHover: (
    key: string | null
  ) => void;

  onSelect: (key: string) => void;
}) {
  const size = 700;
  const center = size / 2;
  const radiusValue = 292;

  function position(
    emotion: Emotion
  ) {
    const x =
      center +
      emotion.valence *
        radiusValue *
        0.86;

    const y =
      center -
      emotion.arousal *
        radiusValue *
        0.86;

    return {
      x: clamp(x, 90, 610),
      y: clamp(y, 82, 618),
    };
  }

  const activeEmotion =
    emotions.find(
      (emotion) =>
        emotion.key === activeKey
    ) ?? null;

  return (
    <div
      className="overflow-hidden p-3 sm:p-5"
      style={{
        backgroundColor: C.surface,
        borderRadius: radius.lg,
      }}
    >
      <svg
        viewBox={`0 0 ${size} ${size}`}
        className="h-auto w-full"
        role="img"
        aria-label="Карта эмоциональных состояний по приятности переживания и уровню активации"
        onMouseLeave={() =>
          onHover(null)
        }
      >
        <defs>
          <clipPath id="emotion-circle">
            <circle
              cx={center}
              cy={center}
              r={radiusValue}
            />
          </clipPath>
        </defs>

        {/* QUADRANTS */}

        <g
          clipPath="url(#emotion-circle)"
        >
          <rect
            x={center}
            y={55}
            width={310}
            height={295}
            fill={C.ochre}
            opacity="0.11"
          />

          <rect
            x={55}
            y={55}
            width={295}
            height={295}
            fill={C.terracotta}
            opacity="0.09"
          />

          <rect
            x={55}
            y={center}
            width={295}
            height={310}
            fill={C.berry}
            opacity="0.065"
          />

          <rect
            x={center}
            y={center}
            width={310}
            height={310}
            fill={C.moss}
            opacity="0.095"
          />
        </g>

        {/* OUTER CIRCLE */}

        <circle
          cx={center}
          cy={center}
          r={radiusValue}
          fill="none"
          stroke={C.line}
          strokeWidth="1.4"
        />

        {/* AXES */}

        <line
          x1={center}
          y1={62}
          x2={center}
          y2={638}
          stroke={C.line}
          strokeWidth="1"
        />

        <line
          x1={62}
          y1={center}
          x2={638}
          y2={center}
          stroke={C.line}
          strokeWidth="1"
        />

        <circle
          cx={center}
          cy={center}
          r="4"
          fill={C.line}
        />

        {/* AXIS LABELS */}

        <text
          x={center}
          y="37"
          textAnchor="middle"
          fontSize="13"
          fill={C.inkSoft}
          style={sans}
        >
          больше активации · больше энергии
        </text>

        <text
          x={center}
          y="680"
          textAnchor="middle"
          fontSize="13"
          fill={C.inkSoft}
          style={sans}
        >
          меньше активации · меньше энергии
        </text>

        <text
          x="22"
          y={center + 4}
          textAnchor="start"
          fontSize="13"
          fill={C.inkSoft}
          style={sans}
        >
          неприятнее
        </text>

        <text
          x="678"
          y={center + 4}
          textAnchor="end"
          fontSize="13"
          fill={C.inkSoft}
          style={sans}
        >
          приятнее
        </text>

        {/* EMOTIONS */}

        {emotions.map(
          (emotion) => {
            const { x, y } =
              position(emotion);

            const active =
              activeKey ===
              emotion.key;

            const selected =
              selectedKey ===
              emotion.key;

            const width =
              clamp(
                emotion.name.length *
                  7.4 +
                  30,
                74,
                132
              );

            return (
              <g
                key={emotion.key}
                role="button"
                tabIndex={0}
                aria-label={
                  emotion.name
                }
                onMouseEnter={() =>
                  onHover(
                    emotion.key
                  )
                }
                onMouseLeave={() =>
                  onHover(null)
                }
                onClick={() =>
                  onSelect(
                    emotion.key
                  )
                }
                onKeyDown={(
                  event
                ) => {
                  if (
                    event.key ===
                      'Enter' ||
                    event.key === ' '
                  ) {
                    event.preventDefault();

                    onSelect(
                      emotion.key
                    );
                  }
                }}
                style={{
                  cursor: 'pointer',
                  outline: 'none',
                }}
              >
                <rect
                  x={
                    x -
                    width / 2
                  }
                  y={y - 17}
                  width={width}
                  height="34"
                  rx="17"
                  fill={
                    selected
                      ? C.ink
                      : active
                        ? C.surfaceWarm
                        : C.bg
                  }
                  stroke={
                    selected ||
                    active
                      ? C.ink
                      : C.line
                  }
                  strokeWidth={
                    selected
                      ? 1.5
                      : 1
                  }
                />

                <text
                  x={x}
                  y={y + 4}
                  textAnchor="middle"
                  fontSize="12"
                  fontWeight={
                    selected
                      ? 600
                      : 400
                  }
                  fill={
                    selected
                      ? C.bg
                      : C.ink
                  }
                  style={{
                    ...sans,
                    pointerEvents:
                      'none',
                  }}
                >
                  {emotion.name}
                </text>
              </g>
            );
          }
        )}

        {/* CENTER */}

        <circle
  cx={center}
  cy={center}
  r="54"
  fill={C.bg}
  stroke={C.line}
  strokeWidth="1"
  pointerEvents="none"
/>

<text
  x={center}
  y={center - 5}
  textAnchor="middle"
  fontSize="10"
  fill={C.inkSoft}
  style={{
    ...sans,
    pointerEvents: 'none',
  }}
>
  наведите
</text>

<text
  x={center}
  y={center + 12}
  textAnchor="middle"
  fontSize="10"
  fill={C.inkSoft}
  style={{
    ...sans,
    pointerEvents: 'none',
  }}
>
  или нажмите
</text>

        {!activeEmotion && (
          <text
            x={center}
            y={center + 13}
            textAnchor="middle"
            fontSize="10"
            fill={C.inkSoft}
            style={{
              ...sans,
              pointerEvents:
                'none',
            }}
          >
            состояние
          </text>
        )}
      </svg>
    </div>
  );
}

